import sys
import os
import json
from decimal import Decimal
from datetime import date, datetime

sys.path.insert(0, os.path.abspath("."))
from app.core.database import SessionLocal
from app.models.fee import FeeStructure, StudentFee, FeePayment
from app.models.school_class import SchoolClass
from app.models.student import Student
from app.models.student_enrollment import StudentEnrollment

def default_serializer(obj):
    if isinstance(obj, (datetime, date)):
        return obj.isoformat()
    if isinstance(obj, Decimal):
        return float(obj)
    return str(obj)

def backup_and_clean():
    db = SessionLocal()
    os.makedirs("backups", exist_ok=True)
    backup_path = os.path.join("backups", f"fees_backup_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json")

    print("=== STEP 1: TAKING FULL BACKUP OF FEES DATA ===")
    backup_data = {
        "fee_structures": [
            {
                "id": fs.id,
                "name": fs.name,
                "academic_year": fs.academic_year,
                "class_id": fs.class_id,
                "amount": float(fs.amount),
                "frequency": fs.frequency,
                "due_date": fs.due_date.isoformat() if fs.due_date else None,
                "description": fs.description,
                "status": fs.status,
                "created_at": fs.created_at.isoformat() if fs.created_at else None,
            }
            for fs in db.query(FeeStructure).all()
        ],
        "student_fees": [
            {
                "id": sf.id,
                "invoice_number": sf.invoice_number,
                "student_id": sf.student_id,
                "class_id": sf.class_id,
                "fee_structure_id": sf.fee_structure_id,
                "academic_year": sf.academic_year,
                "fee_type": sf.fee_type,
                "amount_due": float(sf.amount_due),
                "discount_amount": float(sf.discount_amount),
                "due_date": sf.due_date.isoformat() if sf.due_date else None,
                "status": sf.status,
                "created_at": sf.created_at.isoformat() if sf.created_at else None,
            }
            for sf in db.query(StudentFee).all()
        ],
        "fee_payments": [
            {
                "id": fp.id,
                "student_fee_id": fp.student_fee_id,
                "student_id": fp.student_id,
                "receipt_number": fp.receipt_number,
                "amount_paid": float(fp.amount_paid),
                "payment_date": fp.payment_date.isoformat() if fp.payment_date else None,
                "payment_method": fp.payment_method,
                "reference_number": fp.reference_number,
                "recorded_by_id": fp.recorded_by_id,
                "notes": fp.notes,
                "status": fp.status,
                "created_at": fp.created_at.isoformat() if fp.created_at else None,
            }
            for fp in db.query(FeePayment).all()
        ],
        "students": [
            {
                "id": s.id,
                "admission_number": s.admission_number,
                "full_name": s.full_name,
                "status": s.status,
            }
            for s in db.query(Student).all()
        ],
    }

    with open(backup_path, "w", encoding="utf-8") as f:
        json.dump(backup_data, f, indent=2, default=default_serializer)

    print(f"Backup saved to: {backup_path}")
    print(f"Backed up: {len(backup_data['fee_structures'])} fee structures, {len(backup_data['student_fees'])} invoices, {len(backup_data['fee_payments'])} payments, {len(backup_data['students'])} students.")

    print("\n=== STEP 2: IDENTIFYING TEST ARTIFACTS TO CLEAN ===")
    # Legitimate fee structure: ID 150 ("primary monthly fee" created by Admin)
    # Test fee structures: IDs >= 166 (all generated by User 139 / automated tests)
    test_structs = db.query(FeeStructure).filter(FeeStructure.id >= 166).all()
    test_struct_ids = [fs.id for fs in test_structs]
    print(f"Test fee structures to remove: {len(test_struct_ids)} structures (IDs: {test_struct_ids})")

    # Invoices to remove:
    # 1. Invoices attached to test fee structures
    # 2. Invoices with fee_structure_id IS NULL (all 136 orphan test invoices like INV-TEST-*, INV-VOID-*, etc.)
    # In total, all 162 invoices were confirmed to be from test suites.
    all_invoices = db.query(StudentFee).all()
    print(f"Total test invoices to clean: {len(all_invoices)}")

    # All payments are on test invoices (160 test payments)
    all_payments = db.query(FeePayment).all()
    print(f"Total test payments to clean: {len(all_payments)}")

    # Check test class 158 ("Grade 7 - C") which has 0 enrolled students
    class_158 = db.query(SchoolClass).filter(SchoolClass.id == 158).first()
    if class_158:
        print(f"Test class found: ID 158 ({class_158.name}) with 0 enrollments.")

    print("\n=== STEP 3: EXECUTING SAFE CLEANUP IN TRANSACTION ===")
    try:
        # Delete payments first (foreign key to student_fees)
        del_payments_count = db.query(FeePayment).delete(synchronize_session=False)
        print(f"Deleted {del_payments_count} test payments.")

        # Delete invoices
        del_invoices_count = db.query(StudentFee).delete(synchronize_session=False)
        print(f"Deleted {del_invoices_count} test/orphan invoices.")

        # Delete test fee structures
        del_struct_count = db.query(FeeStructure).filter(FeeStructure.id.in_(test_struct_ids)).delete(synchronize_session=False)
        print(f"Deleted {del_struct_count} test fee structures.")

        # Clean test class 158 if present
        if class_158:
            db.delete(class_158)
            print("Deleted test class 158 (Grade 7 - C).")

        db.commit()
        print("Cleanup transaction committed successfully.")
    except Exception as e:
        db.rollback()
        print(f"ERROR during cleanup, transaction rolled back: {e}")
        raise

    print("\n=== STEP 4: VERIFYING POST-CLEANUP INTEGRITY ===")
    remaining_fs = db.query(FeeStructure).all()
    print(f"Remaining Fee Structures ({len(remaining_fs)}):")
    for fs in remaining_fs:
        c_name = fs.school_class.name if fs.school_class else "All Classes"
        print(f"  ID: {fs.id} | Name: {fs.name} | AY: {fs.academic_year} | Class: {c_name} | Amount: {fs.amount} | Status: {fs.status}")

    print(f"Remaining StudentFees: {db.query(StudentFee).count()}")
    print(f"Remaining FeePayments: {db.query(FeePayment).count()}")
    print(f"Remaining Students: {db.query(Student).count()} (All real students preserved)")
    print(f"Remaining Enrollments: {db.query(StudentEnrollment).count()} (All real enrollments preserved)")

    db.close()

if __name__ == "__main__":
    backup_and_clean()
